#!/usr/bin/env python3
"""app2c.py - embed a CE flash application (.8ek) into a C header.

The resident fast-mirror app (calc/resident -> RESIDOCK.8ek) is an *unsigned*
flash app, so it cannot be sent to a stock calculator the normal way; instead an
on-calc installer writes it to a free flash slot and fixes up its relocations
(see docs/RESIDENT.md section 6, modelled on Cesium/AsmHook2 `app_create`). This
tool turns the .8ek into a C header the installer can `#include`: the raw app
image bytes plus the two offsets the installer needs - `code_offset` (where the
relocatable code begins) and `table_offset` (the embedded relocation table).

It writes NO flash and runs on a PC. Output is deterministic.

Usage:
    app2c.py INPUT.8ek OUTPUT.h [--name SYMBOL]

The .8ek is a TIFL flash-file wrapper ("**TIFL**", 78-byte header, a 4-byte
little-endian data length at offset 0x4A, then the app image to EOF). Inside the
image, the eZ80 app header is marked by "eZ8"; the 3-byte little-endian field at
header+0x12 is the code offset relative to the header, and the relocation table
begins 0x2A bytes after the header. These were verified against toolchain output.
"""
import sys

TIFL_MAGIC = b"**TIFL**"
TIFL_HEADER_LEN = 78
TIFL_DATALEN_OFF = 0x4A
EZ8_MARK = b"eZ8"
CODE_FIELD_OFF = 0x12   # u24 LE at header+0x12 = code offset from header
TABLE_FROM_HEADER = 0x2A  # relocation table begins here, after the exe header


def u24(b, o):
    return b[o] | (b[o + 1] << 8) | (b[o + 2] << 16)


def u32(b, o):
    return b[o] | (b[o + 1] << 8) | (b[o + 2] << 16) | (b[o + 3] << 24)


def parse_8ek(raw):
    if raw[:len(TIFL_MAGIC)] != TIFL_MAGIC:
        raise ValueError("not a TIFL (.8ek) file: bad magic")
    datalen = u32(raw, TIFL_DATALEN_OFF)
    image = raw[TIFL_HEADER_LEN:TIFL_HEADER_LEN + datalen]
    if len(image) != datalen:
        raise ValueError("truncated .8ek: data length %d, have %d"
                         % (datalen, len(image)))
    hs = image.find(EZ8_MARK)
    if hs < 0:
        raise ValueError("no 'eZ8' app header found in image")
    code_offset = hs + u24(image, hs + CODE_FIELD_OFF)
    table_offset = hs + TABLE_FROM_HEADER
    if not (0 < table_offset < code_offset <= len(image)):
        raise ValueError("implausible offsets: table=%d code=%d size=%d"
                         % (table_offset, code_offset, len(image)))
    return image, code_offset, table_offset


def emit(image, code_offset, table_offset, sym, src):
    out = []
    out.append("/* Generated by calc/tools/app2c.py from %s - do not edit. */" % src)
    out.append("#ifndef %s_H" % sym.upper())
    out.append("#define %s_H" % sym.upper())
    out.append("")
    out.append("#define %s_SIZE %uu" % (sym.upper(), len(image)))
    out.append("#define %s_CODE_OFFSET %uu" % (sym.upper(), code_offset))
    out.append("#define %s_TABLE_OFFSET %uu" % (sym.upper(), table_offset))
    out.append("")
    out.append("static const unsigned char %s_image[%u] = {" % (sym, len(image)))
    for i in range(0, len(image), 16):
        row = ", ".join("0x%02x" % b for b in image[i:i + 16])
        out.append("    %s," % row)
    out.append("};")
    out.append("")
    out.append("#endif")
    out.append("")
    return "\n".join(out)


def main(argv):
    args = [a for a in argv[1:] if not a.startswith("--")]
    sym = "dock_app"
    for a in argv[1:]:
        if a.startswith("--name="):
            sym = a.split("=", 1)[1]
    if len(args) < 2:
        sys.stderr.write("usage: app2c.py INPUT.8ek OUTPUT.h [--name=SYMBOL]\n")
        return 2
    raw_mode = "--raw" in argv
    inp, outp = args[0], args[1]
    raw = open(inp, "rb").read()
    image, code_offset, table_offset = parse_8ek(raw)
    if raw_mode:
        # Just the app image bytes, e.g. for a fasmg `file` include.
        open(outp, "wb").write(image)
    else:
        open(outp, "w").write(emit(image, code_offset, table_offset, sym, inp))
    sys.stderr.write("app2c: %s -> %s (%d bytes, code@%d, reloc table@%d)\n"
                     % (inp, outp, len(image), code_offset, table_offset))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
